"""Offline translation interface. Backends never receive file contents."""
from pathlib import Path
from typing import Protocol
import json
import os
import re
from model_setup import MODEL_DIR, ready

PERSIAN = re.compile(r'[\u0620-\u063f\u0641-\u064a\u066e-\u066f\u0671-\u06d3\u06d5\u06ee-\u06ef\u06fa-\u06fc\u06ff\u0750-\u077f\u08a0-\u08c9\ufb50-\ufdff\ufe70-\ufefc]')
PROTECTED = re.compile(r'[A-Za-z0-9]+(?:[._-][A-Za-z0-9]+)*|[\d]+(?:[._-][\d]+)*')


class QuickMTBackend:
    """Local FA->EN neural model with deterministic decoding and in-memory phrase cache."""
    def __init__(self):
        if not ready():
            raise RuntimeError('مدل QuickMT نصب نیست. install_neural.bat را یک بار اجرا کنید؛ سپس برنامه را دوباره باز کنید.')
        try:
            import ctranslate2
            import sentencepiece
        except ImportError as exc:
            raise RuntimeError('کتابخانه ترجمه نصب نیست؛ install_neural.bat را اجرا کنید.') from exc
        self.engine = ctranslate2.Translator(str(MODEL_DIR), device='cpu', compute_type='int8',
                                            inter_threads=1, intra_threads=min(4, os.cpu_count() or 2))
        self.encoder = sentencepiece.SentencePieceProcessor(model_proto=(MODEL_DIR / 'src.spm.model').read_bytes())
        self.decoder = sentencepiece.SentencePieceProcessor(model_proto=(MODEL_DIR / 'tgt.spm.model').read_bytes())
        self.cache = {}
        self.glossary = GlossaryBackend()

    def phrase(self, text):
        text = re.sub(r'[_\s]+', ' ', text.replace('\u200c', ' ')).strip(' -_.,،؛')
        text = text.translate(str.maketrans({'ي': 'ی', 'ك': 'ک'}))
        if not text:
            return ''
        if text not in self.cache:
            tokens = self.encoder.encode(text, out_type=str) + ['</s>']
            if len(tokens) > 240:
                return None
            response = self.engine.translate_batch([tokens], beam_size=5, max_input_length=0,
                max_decoding_length=256, repetition_penalty=1.05, disable_unk=True)[0]
            result = self.decoder.decode(response.hypotheses[0]).strip().rstrip('.')
            # Never silently accept dropped Persian, hallucinated IDs, or truncated decoding.
            if not result or PERSIAN.search(result) or len(response.hypotheses[0]) >= 256 or re.search(r'\d', result):
                return None
            self.cache[text] = result
        return self.cache[text]

    def translate(self, text):
        exact = self.glossary.translate(text)
        if exact:
            return exact
        pieces = []
        cursor = 0
        # English identifiers and numeric strings are copied, never generated by the model.
        for match in PROTECTED.finditer(text):
            fragment = text[cursor:match.start()]
            if PERSIAN.search(fragment):
                fragment = self.phrase(fragment)
                if not fragment:
                    return None
            fragment = fragment.strip(' _-.,،؛')
            if fragment:
                pieces.append(fragment)
            pieces.append(match.group())
            cursor = match.end()
        fragment = text[cursor:]
        if PERSIAN.search(fragment):
            fragment = self.phrase(fragment)
            if not fragment:
                return None
        fragment = fragment.strip(' _-.,،؛')
        if fragment:
            pieces.append(fragment)
        result = ' '.join(pieces)
        # Make model punctuation a valid filename, visibly in preview; engine still validates collisions.
        result = re.sub(r'[<>:"/\\|?*\x00-\x1f]', ' - ', result)
        result = re.sub(r'\s+', ' ', result).strip(' .')
        return result or None


class Backend(Protocol):
    def translate(self, text: str) -> str | None: ...


class GlossaryBackend:
    """Exact phrase lookup; missing phrases deliberately remain unresolved."""
    def __init__(self, path=None):
        self.words = json.loads(Path(path or Path(__file__).with_name('glossary.json')).read_text(encoding='utf-8'))

    def translate(self, text):
        return self.words.get(text)


class ArgosBackend:
    def __init__(self):
        try:
            from argostranslate import translate
        except ImportError as exc:
            raise RuntimeError('ابتدا requirements-offline.txt را نصب کنید.') from exc
        languages = translate.get_installed_languages()
        source = next((x for x in languages if x.code == 'fa'), None)
        target = next((x for x in languages if x.code == 'en'), None)
        if not source or not target:
            raise RuntimeError('مدل محلی فارسی به انگلیسی Argos نصب نیست؛ مدل سازگار را نصب کنید یا از واژه‌نامه و ویرایش دستی استفاده کنید.')
        self.engine = source.get_translation(target)
        if self.engine is None:
            raise RuntimeError('مسیر ترجمه فارسی به انگلیسی در مدل‌های نصب‌شده وجود ندارد.')

    def translate(self, text):
        return self.engine.translate(text)


def suggest(name, kind, backend):
    if not PERSIAN.search(name):
        return name, 'بدون تغییر'
    # Preserve Latin extension chains, including .tar.gz; Persian suffixes are translated.
    stem, suffix = name, ''
    if kind == 'file':
        match = re.search(r'(\.[A-Za-z0-9]{1,10})+$', name)
        if match:
            stem, suffix = name[:match.start()], match.group()
    result = backend.translate(stem)
    if not result or PERSIAN.search(result):
        return name, getattr(backend, 'last_issue', '') or 'نیازمند ترجمه دستی'
    return result.strip() + suffix, getattr(backend, 'last_issue', '') or 'پیشنهاد — بررسی کنید'
